// Runs vitest (JSON reporter) and writes docs/tests.md: every assertion with pass/fail.
// Optional: pass --e2e to also run the Playwright smoke suite and append its results.
import { execSync } from 'node:child_process'
import { readFileSync, writeFileSync, mkdirSync, rmSync } from 'node:fs'

const tmp = 'node_modules/.cache/vitest-report.json'
mkdirSync('node_modules/.cache', { recursive: true })
try { execSync(`npx vitest run --reporter=json --outputFile=${tmp}`, { stdio: 'ignore' }) } catch { /* failures still write the report */ }
const r = JSON.parse(readFileSync(tmp, 'utf8'))
rmSync(tmp)

const icon = (s) => (s === 'passed' ? '✅ pass' : s === 'skipped' || s === 'pending' ? '⏭ skipped' : '❌ FAIL')
let md = `# Test results\n\nGenerated by \`npm run docs:tests\` on ${new Date().toISOString().slice(0, 10)}.\n\n`
md += `**Unit tests (vitest): ${r.numPassedTests} passed, ${r.numFailedTests} failed, ${r.numPendingTests} skipped, of ${r.numTotalTests}.**\n\n`
md += 'Every figure in the submitted deck is asserted exactly in `src/lib/model.test.ts`. If a test fails, the model is fixed, never the test.\n'

for (const file of r.testResults.sort((a, b) => a.name.localeCompare(b.name))) {
  const rel = file.name.split(String.fromCharCode(92)).join('/').replace(/^.*?\/(src|tests)\//, '$1/')
  md += `\n## \`${rel}\`\n\n| Group | Assertion | Result |\n|---|---|---|\n`
  for (const t of file.assertionResults) {
    md += `| ${t.ancestorTitles.join(' › ')} | ${t.title.split('|').join('/')} | ${icon(t.status)} |\n`
  }
}

if (process.argv.includes('--e2e')) {
  let out = ''
  try { out = execSync('npx playwright test --reporter=line', { encoding: 'utf8' }) } catch (e) { out = String(e.stdout ?? e) }
  const summary = out.split('\n').filter((l) => /passed|failed|flaky/.test(l)).join('\n').trim()
  md += `\n## End-to-end smoke (Playwright, 360 / 768 / 1440 px)\n\n\`\`\`\n${summary}\n\`\`\`\n\nScreenshots: [docs/screens](./screens).\n`
}

writeFileSync('docs/tests.md', md)
console.log('docs/tests.md written')
